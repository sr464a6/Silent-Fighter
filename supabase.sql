-- =========================================================
-- REMOVE OLD TABLE
-- =========================================================

DROP TABLE IF EXISTS leaderboard;


-- =========================================================
-- CREATE LEADERBOARD
-- =========================================================

CREATE TABLE leaderboard (

    id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    player_name TEXT
        NOT NULL
        DEFAULT 'Anonymous',

    score INTEGER
        NOT NULL
        DEFAULT 0,

    max_combo INTEGER
        NOT NULL
        DEFAULT 0,

    damage INTEGER
        NOT NULL
        DEFAULT 0,

    created_at TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW()

);


-- =========================================================
-- VALIDATION
-- =========================================================

ALTER TABLE leaderboard

ADD CONSTRAINT
leaderboard_player_name_length

CHECK (
    char_length(player_name)
    BETWEEN 1 AND 20
);


ALTER TABLE leaderboard

ADD CONSTRAINT
leaderboard_score_positive

CHECK (
    score >= 0
);


ALTER TABLE leaderboard

ADD CONSTRAINT
leaderboard_combo_positive

CHECK (
    max_combo >= 0
);


ALTER TABLE leaderboard

ADD CONSTRAINT
leaderboard_damage_positive

CHECK (
    damage >= 0
);


-- =========================================================
-- INDEX
-- =========================================================

CREATE INDEX
leaderboard_score_idx

ON leaderboard (
    score DESC
);


CREATE INDEX
leaderboard_created_at_idx

ON leaderboard (
    created_at DESC
);


-- =========================================================
-- ROW LEVEL SECURITY
-- =========================================================

ALTER TABLE leaderboard
ENABLE ROW LEVEL SECURITY;


-- =========================================================
-- PUBLIC READ
-- =========================================================

CREATE POLICY
"Public can read leaderboard"

ON leaderboard

FOR SELECT

TO anon, authenticated

USING (
    true
);


-- =========================================================
-- PUBLIC INSERT
-- =========================================================

CREATE POLICY
"Public can submit scores"

ON leaderboard

FOR INSERT

TO anon, authenticated

WITH CHECK (
    char_length(player_name)
    BETWEEN 1 AND 20

    AND

    score >= 0

    AND

    max_combo >= 0

    AND

    damage >= 0
);


